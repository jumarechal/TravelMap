// Liste des pays du monde (code ISO 3166-1 + nom en français + continent),
// utilisée par l'écran Passeport pour afficher un badge par pays, regroupé
// par continent.

// Construit l'emoji drapeau à partir d'un code pays à 2 lettres (ex: "FR" -> 🇫🇷)
function getFlagEmoji(code) {
  return String.fromCodePoint(
    ...code
      .toUpperCase()
      .split('')
      .map((char) => 127397 + char.charCodeAt(0))
  );
}

