// superficie approximative en km², capitale "pratique" - celle où l'on est
// le plus susceptible de se rendre, pas toujours la capitale officielle -,
// et coordonnées approximatives de cette capitale (utilisées pour calculer
// une distance à vol d'oiseau, ex : suggestions de voyage par proximité).
// Utilisée par l'écran Passeport (badges) et pour le calcul du niveau de
// connaissance d'un pays (superficie -> score nécessaire, capitale -> bonus).

// Construit l'emoji drapeau à partir d'un code pays à 2 lettres (ex: "FR" -> 🇫🇷)
function getFlagEmoji(code) {
  return String.fromCodePoint(
    ...code
      .toUpperCase()
      .split('')
      .map((char) => 127397 + char.charCodeAt(0))
  );
}

